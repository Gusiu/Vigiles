CREATE TRIGGER work_orders_touch BEFORE INSERT OR UPDATE ON work_orders
    FOR EACH ROW EXECUTE FUNCTION touch_versioned_row();
CREATE TRIGGER inspections_touch BEFORE INSERT OR UPDATE ON inspections
    FOR EACH ROW EXECUTE FUNCTION touch_versioned_row();
CREATE TRIGGER conflicts_touch BEFORE INSERT OR UPDATE ON conflicts
    FOR EACH ROW EXECUTE FUNCTION touch_versioned_row();

-- After each change: snapshot into entity_history and an entry in the
-- change feed. SECURITY DEFINER lets the importer trigger it without
-- direct privileges on the history tables.
CREATE FUNCTION record_change() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    INSERT INTO entity_history (entity, entity_id, rev, data, origin)
    VALUES (TG_ARGV[0], NEW.id, NEW.rev, to_jsonb(NEW), NEW.origin);
    INSERT INTO change_log (entity, entity_id, rev, op, origin)
    VALUES (TG_ARGV[0], NEW.id, NEW.rev, lower(TG_OP), NEW.origin);
    RETURN NULL;
END;
$$;

CREATE TRIGGER assets_record AFTER INSERT OR UPDATE ON assets
    FOR EACH ROW EXECUTE FUNCTION record_change('asset');
CREATE TRIGGER work_orders_record AFTER INSERT OR UPDATE ON work_orders
    FOR EACH ROW EXECUTE FUNCTION record_change('work_order');
CREATE TRIGGER inspections_record AFTER INSERT OR UPDATE ON inspections
    FOR EACH ROW EXECUTE FUNCTION record_change('inspection');
CREATE TRIGGER conflicts_record AFTER INSERT OR UPDATE ON conflicts
    FOR EACH ROW EXECUTE FUNCTION record_change('conflict');


INSERT INTO entity_history (entity, entity_id, rev, data, origin)
SELECT 'asset', id, rev, to_jsonb(assets), origin FROM assets;
INSERT INTO change_log (entity, entity_id, rev, op, origin)
SELECT 'asset', id, rev, 'insert', origin FROM assets ORDER BY code;

-- Two-way synchronisation with the field app (grade 4.0): work orders,
-- inspections, incidents, revision history, change feed, conflicts,
-- idempotency, integration events and the webhook outbox.

CREATE TABLE work_orders (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    asset_id       uuid NOT NULL REFERENCES assets (id),
    reason         text NOT NULL CHECK (reason IN (
                       'przeglad_okresowy', 'usterka_urzadzenia', 'czyszczenie', 'brak_lacznosci')),
    status         text NOT NULL DEFAULT 'nowe' CHECK (status IN (
                       'nowe', 'przydzielone', 'w_realizacji', 'zakonczone', 'anulowane')),
    assigned_to    text,
    due_date       date,
    description    text,
    source         text NOT NULL DEFAULT 'manual',
    correlation_id text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    rev            integer NOT NULL DEFAULT 1,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    updated_by     text,
    origin         text
);

-- At most one open order per asset and reason: repeated faults from a
-- device must not create duplicates.
CREATE UNIQUE INDEX work_orders_one_open_idx ON work_orders (asset_id, reason)
    WHERE status IN ('nowe', 'przydzielone', 'w_realizacji');

CREATE TABLE inspections (
    id             uuid PRIMARY KEY,  -- generated by the field app
    work_order_id  uuid REFERENCES work_orders (id),
    asset_id       uuid NOT NULL REFERENCES assets (id),
    technician     text NOT NULL,
    performed_at   timestamptz NOT NULL,
    result         text NOT NULL CHECK (result IN ('sprawny', 'do_naprawy', 'niesprawny')),
    findings       text,
    rev            integer NOT NULL DEFAULT 1,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    updated_by     text,
    origin         text
);

CREATE TABLE incidents (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    kind           text NOT NULL CHECK (kind IN ('alarm_potwierdzony', 'alarm_wstepny')),
    site           text NOT NULL,
    zone           text NOT NULL,
    detectors      text[] NOT NULL,
    first_at       timestamptz NOT NULL,
    decided_at     timestamptz NOT NULL,
    correlation_id text,
    status         text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE conflicts (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    entity           text NOT NULL,
    entity_id        uuid NOT NULL,
    field            text NOT NULL,
    base_value       jsonb,
    server_value     jsonb,
    client_value     jsonb,
    client_change_id uuid NOT NULL,
    status           text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
    resolved_by      text,
    resolved_value   jsonb,
    created_at       timestamptz NOT NULL DEFAULT now(),
    resolved_at      timestamptz,
    rev              integer NOT NULL DEFAULT 1,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       text,
    origin           text
);

CREATE INDEX conflicts_open_idx ON conflicts (entity, entity_id) WHERE status = 'open';

-- Every revision of a synchronised entity: base for the three-way merge
-- and audit trail.
CREATE TABLE entity_history (
    entity     text NOT NULL,
    entity_id  uuid NOT NULL,
    rev        integer NOT NULL,
    data       jsonb NOT NULL,
    origin     text,
    changed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (entity, entity_id, rev)
);

-- Change feed read by the field app: GET /sync/changes?since=seq.
CREATE TABLE change_log (
    seq        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entity     text NOT NULL,
    entity_id  uuid NOT NULL,
    rev        integer NOT NULL,
    op         text NOT NULL CHECK (op IN ('insert', 'update')),
    origin     text,
    changed_at timestamptz NOT NULL DEFAULT now()
);

-- Idempotent Receiver for /sync/push: the stored result is returned when
-- the same change_id arrives again.
CREATE TABLE applied_changes (
    change_id  uuid PRIMARY KEY,
    result     jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Idempotent Receiver for creating calls from services (Idempotency-Key).
CREATE TABLE idempotency_keys (
    client_id   text NOT NULL,
    key         text NOT NULL,
    status_code integer NOT NULL,
    response    jsonb NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (client_id, key)
);

CREATE TABLE integration_events (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ts             timestamptz NOT NULL DEFAULT now(),
    service        text NOT NULL,
    event          text NOT NULL,
    correlation_id text,
    outcome        text NOT NULL,
    details        jsonb NOT NULL DEFAULT '{}'
);

CREATE INDEX integration_events_correlation_idx ON integration_events (correlation_id);

-- Transactional outbox for outgoing HTTP calls (webhooks to the field app).
CREATE TABLE outbox (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message_id      uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    kind            text NOT NULL,
    method          text NOT NULL DEFAULT 'POST',
    target_url      text NOT NULL,
    payload         jsonb NOT NULL,
    headers         jsonb NOT NULL DEFAULT '{}',
    status          text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'dead')),
    attempts        integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    locked_by       text,
    locked_until    timestamptz,
    last_error      text,
    correlation_id  text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    sent_at         timestamptz
);

CREATE INDEX outbox_due_idx ON outbox (next_attempt_at) WHERE status = 'pending';

CREATE TABLE notifier_state (
    id       boolean PRIMARY KEY DEFAULT true CHECK (id),
    last_seq bigint NOT NULL DEFAULT 0
);
